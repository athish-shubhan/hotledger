#!/usr/bin/env python3
"""Turn results/runs/*/result.json into figures and results/SUMMARY.md."""
import glob
import json
import os
import statistics
import sys

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt

runs_dir, out_dir = sys.argv[1], sys.argv[2]
os.makedirs(out_dir, exist_ok=True)
R = {}
for p in sorted(glob.glob(os.path.join(runs_dir, "*", "result.json"))):
    R[os.path.basename(os.path.dirname(p))] = json.load(open(p))

DESIGNS = ["rowlock", "mysql-rowlock", "condupdate", "mysql-condupdate", "escrow", "escrow-hint", "redislua", "kafka", "tigerbeetle"]
LABEL = {
    "rowlock": "1 row lock, Postgres",
    "mysql-rowlock": "1 row lock, MySQL",
    "condupdate": "2 conditional update, Postgres",
    "mysql-condupdate": "2 conditional update, MySQL",
    "escrow": "3 escrow, 16 slots",
    "escrow-hint": "3 escrow + sold-out hint",
    "redislua": "4 Redis Lua + async log",
    "kafka": "5 Kafka single writer",
    "tigerbeetle": "6 TigerBeetle",
}
COLOR = {"rowlock": "#9aa5b1", "mysql-rowlock": "#c3c9d0", "condupdate": "#5b8def", "mysql-condupdate": "#9dbcf5",
         "escrow": "#2bb3a3", "escrow-hint": "#7fd6cb", "kafka": "#e8a33d", "redislua": "#c75b7a", "tigerbeetle": "#6a51a3"}
SKEWS = ["0.99", "1.5", "2.0"]
SEMS = ["wallet", "inventory", "auction"]
SEMTITLE = {"wallet": "gift wallet", "inventory": "flash-sale inventory", "auction": "countdown auction"}


def g(r, *ks, default=None):
    for k in ks:
        if r is None or not isinstance(r, dict) or k not in r:
            return default
        r = r[k]
    return r


def violations(r):
    """'0' or a short list of violated invariants (system of record and durable copy)."""
    out = []
    for key, tag in (("check", ""), ("check_postgres", "pg copy: "), ("auction_check", ""), ("auction_check_postgres", "pg copy: ")):
        c = r.get(key)
        if not c:
            continue
        for v in c.get("violations") or []:
            name = v['invariant'].split(' ')[0] + (" (Porcupine)" if "Porcupine" in v['invariant'] else "")
            out.append(f"{tag}{name} x{v['count']}")
    if r.get("redis_postgres_agreement", "identical") not in ("identical", ""):
        out.append("redis/pg diverged")
    return "0" if not out else "; ".join(out)


def nfaults(r):
    f = g(r, "config", "Faults", default="") or ""
    return len([x for x in f.split(",") if x.strip()])


def cpu(r):
    v = g(r, "cpu", "server_cpu_sec_per_million_ops")
    return "" if v is None else f"{v:.0f}"


def fmt(v, nd=1):
    return "" if v is None else f"{v:.{nd}f}"


md = ["# HotLedger results", "",
      "Generated by `bench/plot.py` from `results/runs/*/result.json`. One 2-vCPU VM: clients, databases, brokers and writers share it, "
      "so absolute numbers are small; compare designs with each other. CPU is server-side CPU seconds per million operations "
      "(databases, Redis, TigerBeetle, broker, writers, reconciler; not the load generator).", "",
      "**Run-to-run noise.** Each configuration ran once (fault scenarios up to three times). The skew runs of designs 1-4 and 6 ran on an "
      "earlier instance of the same VM type than everything else; three calibration runs on the later instance (`results/calib/`) were 4-5% "
      "slower. Design 5 is the noisiest: two identical wallet runs at s = 2.0 gave 4.0k and 5.2k ops/s (`results/profile/`), and its "
      "flash-sale burst p99 was 2.6 s in an earlier run (before its batch planning was rewritten, so not a clean repeat) and 69 ms in the final one. Differences of a few tens of percent between designs are within noise; "
      "the 2x to 30x gaps are not.", ""]

# ---------------------------------------------------------------- skew
fig, axes = plt.subplots(2, 3, figsize=(16, 7.5))
for col, sem in enumerate(SEMS):
    have = [d for d in DESIGNS if any(f"skew-{sem}-{d}-{s}" in R for s in SKEWS)]
    if not have:
        continue
    w = 0.85 / len(have)
    for i, d in enumerate(have):
        xs = [j + i * w for j in range(len(SKEWS))]
        thr = [g(R.get(f"skew-{sem}-{d}-{s}"), "load", "throughput_ops_per_sec", default=0) for s in SKEWS]
        p99 = [g(R.get(f"skew-{sem}-{d}-{s}"), "load", "latency_ms", "p99", default=0) or 0 for s in SKEWS]
        axes[0][col].bar(xs, thr, w, label=LABEL[d], color=COLOR[d])
        axes[1][col].bar(xs, p99, w, label=LABEL[d], color=COLOR[d])
    for row, (t, yl) in enumerate((("throughput", "ops/s"), ("client p99", "ms (log)"))):
        ax = axes[row][col]
        ax.set_xticks([j + 0.425 - w / 2 for j in range(len(SKEWS))])
        ax.set_xticklabels([f"s={s}" for s in SKEWS])
        ax.set_title(f"{SEMTITLE[sem]}: {t}")
        ax.set_ylabel(yl)
        ax.grid(axis="y", alpha=0.3)
    axes[1][col].set_yscale("log")
handles, labels = {}, {}
for ax in axes[0]:
    for h, l in zip(*ax.get_legend_handles_labels()):
        handles[l] = h
fig.legend(list(handles.values()), list(handles.keys()), loc="lower center", ncol=5, fontsize=8, bbox_to_anchor=(0.5, -0.05))
fig.text(0.5, -0.08, "Closed loop, 64 clients, 30 s. Kafka wallet/inventory: client latency is enqueue (broker ack), apply latency in the tables. "
         "Auction clients wait for the decision in every design.", ha="center", fontsize=8)
fig.tight_layout()
fig.savefig(os.path.join(out_dir, "throughput_vs_skew.png"), dpi=130, bbox_inches="tight")
plt.close(fig)

share = {"0.99": "~10%", "1.5": "~38%", "2.0": "~61%"}
for sem in SEMS:
    have = [d for d in DESIGNS if any(f"skew-{sem}-{d}-{s}" in R for s in SKEWS)]
    if not have:
        continue
    what = {"wallet": "gifts (98%) and withdrawals (2%) over 10,000 creators",
            "inventory": "purchases over 10,000 SKUs, stock never runs out (pure bounded-decrement contention)",
            "auction": "bids (90%) and reads (10%) over 200 auctions, deadlines after the run"}[sem]
    md += [f"## {SEMTITLE[sem].capitalize()} vs skew (closed loop, 64 clients, 30 s, 1% duplicate submissions)", "", what + ".", "",
           "| design | Zipf s | hottest key share | ops/s | p50 ms | p99 ms | apply p99 ms (async) | CPU s / M ops | violations |",
           "|---|---|---|---|---|---|---|---|---|"]
    for d in have:
        for s in SKEWS:
            r = R.get(f"skew-{sem}-{d}-{s}")
            if not r:
                continue
            e2e = g(r, "e2e_latency_ms", "p99")
            md.append(f"| {LABEL[d]} | {s} | {share[s]} | {g(r,'load','throughput_ops_per_sec'):.0f} | "
                      f"{fmt(g(r,'load','latency_ms','p50'))} | {fmt(g(r,'load','latency_ms','p99'))} | "
                      f"{'' if e2e is None else f'{e2e:.0f}'} | {cpu(r)} | {violations(r)} |")
    md.append("")

# ---------------------------------------------------------------- burst
fig, axes = plt.subplots(1, 3, figsize=(16, 4.2))
for col, sem in enumerate(SEMS):
    names = [d for d in DESIGNS if f"burst-{sem}-{d}" in R]
    vals = [g(R[f"burst-{sem}-{d}"], "load", "burst_latency_ms", "p99", default=0) or 0 for d in names]
    ax = axes[col]
    ax.barh([LABEL[d] for d in names], vals, color=[COLOR[d] for d in names])
    ax.set_xscale("log")
    ax.set_title(f"{SEMTITLE[sem]}: p99 during the 10x burst")
    ax.set_xlabel("ms (log)")
    ax.grid(axis="x", alpha=0.3)
    for y, v in enumerate(vals):
        ax.text(v, y, f" {v:,.0f}", va="center", fontsize=7)
fig.tight_layout()
fig.savefig(os.path.join(out_dir, "burst_p99.png"), dpi=130, bbox_inches="tight")
plt.close(fig)

for sem in SEMS:
    names = [d for d in DESIGNS if f"burst-{sem}-{d}" in R]
    if not names:
        continue
    what = {"wallet": "LIVE Match end: 500 ops/s for 20 s, then 5,000 ops/s for 10 s of gifts to the two battling creators.",
            "inventory": "Flash sale: 500 ops/s for 20 s, then 5,000 ops/s for 10 s of orders for two SKUs with 10,000 units each, which sell out during the burst.",
            "auction": "Auction end: 500 ops/s for 20 s, then 5,000 ops/s for 10 s of bids on the two hot auctions, which close at 22 s (Extended mode: a bid in the last 2 s extends to ts + 2 s, at most 6 s past the deadline). 'Placed' is the bid's due time on the client: a bid placed before the deadline but stamped after it lost to queueing, not to the bidder."}[sem]
    md += [f"## {SEMTITLE[sem].capitalize()}: 10x burst (open loop)", "", what + " Latency is measured from each request's due time.", ""]
    if sem == "auction":
        md += ["| design | burst p50 ms | burst p99 ms | overall p99 ms | accepted | closed rejections | of which placed before the final deadline | extensions | CPU s / M ops | violations |",
               "|---|---|---|---|---|---|---|---|---|---|"]
    elif sem == "inventory":
        md += ["| design | burst p50 ms | burst p99 ms | overall p99 ms | units sold (hot SKUs) | rejections | apply p99 ms (async) | CPU s / M ops | violations |",
               "|---|---|---|---|---|---|---|---|---|"]
    else:
        md += ["| design | burst p50 ms | burst p99 ms | overall p99 ms | apply p99 ms (async) | CPU s / M ops | violations |",
               "|---|---|---|---|---|---|---|"]
    for d in names:
        r = R[f"burst-{sem}-{d}"]
        b50, b99, o99 = g(r, "load", "burst_latency_ms", "p50"), g(r, "load", "burst_latency_ms", "p99"), g(r, "load", "latency_ms", "p99")
        e2e = g(r, "e2e_latency_ms", "p99")
        if sem == "auction":
            ac = r.get("auction_check") or {}
            md.append(f"| {LABEL[d]} | {fmt(b50)} | {fmt(b99)} | {fmt(o99)} | {ac.get('accepted_bids', '')} | {ac.get('closed_rejections', '')} | "
                      f"{ac.get('closed_but_sent_before_deadline', '')} | {ac.get('deadline_extensions', '')} | {cpu(r)} | {violations(r)} |")
        elif sem == "inventory":
            ck = r.get("check") or {}
            sold = f"{ck.get('hot_units_sold', 0):,} of {ck.get('hot_units_sold', 0) + ck.get('hot_units_left', 0):,}"
            rej = max(g(r, 'load', 'results', 'rejected', default=0) or 0, ck.get('recorded_rejections', 0) or 0)
            md.append(f"| {LABEL[d]} | {fmt(b50)} | {fmt(b99)} | {fmt(o99)} | {sold} | {rej:,} | "
                      f"{'' if e2e is None else f'{e2e:.0f}'} | {cpu(r)} | {violations(r)} |")
        else:
            md.append(f"| {LABEL[d]} | {fmt(b50)} | {fmt(b99)} | {fmt(o99)} | {'' if e2e is None else f'{e2e:.0f}'} | {cpu(r)} | {violations(r)} |")
    md.append("")

# ---------------------------------------------------------------- faults
fr = {k: v for k, v in R.items() if k.startswith("faults-")}
if fr:
    tot_faults = sum(nfaults(r) for r in fr.values())
    tot_dups = sum(g(r, "check", "dup_submissions", default=0) or g(r, "auction_check", "dup_submissions", default=0) or 0 for r in fr.values())
    tot_ops = sum(g(r, "check", "ops", default=0) or g(r, "auction_check", "ops", default=0) or 0 for r in fr.values())
    md += ["## Fault injection", "",
           f"{len(fr)} runs, {tot_faults} injected faults (crashes, kill -9, partitions, connection resets, zombie writers, rebalances, failovers), "
           f"{tot_dups:,} duplicate submissions (half racing the original, half after the answer), {tot_ops:,} client operations checked.", "",
           "| run | faults | ops | dup submissions | retries | unknown outcomes | client outage after the crash (ms) | resume after restart (ms) | violations |",
           "|---|---|---|---|---|---|---|---|---|"]
    for k in sorted(fr):
        r = fr[k]
        ck = r.get("auction_check") or r.get("check") or {}
        res = ck.get("results") or {}
        unknown = sum(v for kk, v in res.items() if kk.endswith("unknown"))
        rec = [x for x in (r.get("recovery") or []) if "partition" not in x["fault"]]
        outage = "; ".join(f"{x['client_outage_ms']:.0f}" for x in rec)
        resume = "; ".join(f"{x.get('resume_after_restart_ms', 0):.0f}" for x in rec)
        md.append(f"| {k.replace('faults-', '')} | {g(r,'config','Faults')} | {ck.get('ops', 0):,} | {ck.get('dup_submissions', 0):,} | "
                  f"{g(r,'load','retries', default=0):,} | {unknown} | {outage} | {resume} | {violations(r)} |")
    md.append("")

    # recovery summary per design (crash faults only)
    md += ["### Recovery after a crash (median over runs)", "",
           "Client outage: the longest stretch with no successful client completion in the 30 s after the crash (includes the 2 s the orchestrator "
           "waits before restarting a database or TigerBeetle). Resume: from the restart until the first success of a request sent after it.", "",
           "| design | crash | runs | client outage ms | resume after restart ms | back to 90% throughput ms |", "|---|---|---|---|---|---|"]
    groups = {}
    for k, r in fr.items():
        d = g(r, "config", "Design")
        if k.endswith("-hint"):
            d = "escrow-hint"
        for x in r.get("recovery") or []:
            if "partition" in x["fault"]:
                continue
            groups.setdefault((d, x["fault"]), []).append(x)
    for (d, f), xs in sorted(groups.items(), key=lambda kv: (DESIGNS.index(kv[0][0]) if kv[0][0] in DESIGNS else 99, kv[0][1])):
        med = lambda key: statistics.median([x.get(key, 0) or 0 for x in xs])
        md.append(f"| {LABEL.get(d, d)} | {f} | {len(xs)} | {med('client_outage_ms'):.0f} | {med('resume_after_restart_ms'):.0f} | {med('recover_to_90pct_ms'):.0f} |")
    md.append("")

# ---------------------------------------------------------------- innodb
inn = [k for k in R if k.startswith("innodb-")]
if inn:
    md += ["## InnoDB next-key locks (design 1 on MySQL, idempotency key checked with SELECT ... FOR UPDATE, s = 2.0, 64 clients)", "",
           "| isolation | ops/s | p99 ms | deadlocks (retries) | violations |", "|---|---|---|---|---|"]
    for k in sorted(inn):
        r = R[k]
        md.append(f"| {k.replace('innodb-lockingidem-', '')} | {g(r,'load','throughput_ops_per_sec'):.0f} | {fmt(g(r,'load','latency_ms','p99'))} | "
                  f"{g(r,'load','retries'):,} | {violations(r)} |")
    base = R.get("skew-wallet-mysql-rowlock-2.0")
    if base:
        md.append(f"| (plain read of the key, REPEATABLE READ) | {g(base,'load','throughput_ops_per_sec'):.0f} | {fmt(g(base,'load','latency_ms','p99'))} | "
                  f"{g(base,'load','retries'):,} | {violations(base)} |")
    md.append("")

# ---------------------------------------------------------------- mutants
mut = [k for k in R if k.startswith("mutant-")]
if mut:
    md += ["## Checker validation: seeded bugs", "", "| mutant | what it breaks | caught by |", "|---|---|---|"]
    what = {"nolock": "row lock without FOR UPDATE: lost updates", "onconflict": "INSERT ... ON CONFLICT DO NOTHING: duplicates commit their debit",
            "nodedupe": "writer applies log duplicates", "snapshot": "auction decided on the statement snapshot, not the locked row"}
    for k in sorted(mut):
        r = R[k]
        m = g(r, "config", "Mutant")
        md.append(f"| {k.replace('mutant-', '')} | {what.get(m, m)} | {violations(r)} |")
    md.append("")

open(os.path.join(out_dir, "SUMMARY.md"), "w").write("\n".join(md) + "\n")
print("wrote", os.path.join(out_dir, "SUMMARY.md"))
